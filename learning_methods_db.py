def get_learning_method(grade, subject_en, level, day_index):
    """
    학년, 과목, 레벨, 날짜에 맞는 학습 방법 반환
    """
    keywords = SUBJECT_KEYWORDS.get(grade, {}).get(subject_en, {}).get(level, [])
    if not keywords:
        return None
    
    topic = keywords[day_index % len(keywords)]
    method = LEARNING_METHODS[level]
    
    # 키워드 치환
    if level == "기초":
        step1 = method["step1"].format(keyword=topic["keyword"])
        return {
            "unit": topic["unit"],
            "keyword": topic["keyword"],
            "tip": topic["tip"],
            "step1": step1,
            "step2": method["step2"],
            "step3": method["step3"],
            "step4": method["step4"],
            "step5": method["step5"],
            "step6": method["step6"],
            "duration": 45
        }
    else:
        # 표준, 심화
        step1 = method["step1"].format(keyword=topic["keyword"])
        return {
            "unit": topic["unit"],
            "keyword": topic["keyword"],
            "tip": topic["tip"],
            "step1": step1,
            "step2": method["step2"],
            "step3": method["step3"],
            "duration": 45 if level == "표준" else 50
        }
