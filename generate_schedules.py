# 학생별 맞춤 스케줄 생성
def create_personalized_schedule(student_name, math_level, english_level, korean_level):
    """학생별 맞춤 스케줄 생성"""
    
    schedule = {
        '학생명': student_name,
        '생성일': datetime.now().strftime('%Y-%m-%d'),
        '수학': get_study_plan('수학', math_level),
        '영어': get_study_plan('영어', english_level),
        '국어': get_study_plan('국어', korean_level),
        '총학습시간': f'{(math_level+1)*10 + (english_level+1)*10 + (korean_level+1)*10}분/일'
    }
    
    return schedule

# 모든 학생의 스케줄 생성
all_schedules = []
for idx, row in df_diagnostic.iterrows():
    schedule = create_personalized_schedule(
        row['학생명'],
        row['수학'] if pd.notna(row['수학']) else 2,
        row['영어'] if pd.notna(row['영어']) else 2,
        row['국어'] if pd.notna(row['국어']) else 2
    )
    all_schedules.append(schedule)

